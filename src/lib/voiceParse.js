/**
 * voiceParse — تحليل خفيف (Regex) لإملاء الفني. لا يرسل شيئاً لأي خدمة؛
 * يحوّل نص الكلام لنص صافي موحّد المصطلحات + يكتشف أمر الإنجاز.
 */
const AR_DIGITS = '٠١٢٣٤٥٦٧٨٩';
const toLatinDigits = (s) => s.replace(/[٠-٩]/g, (d) => String(AR_DIGITS.indexOf(d)));

// كلمات الأرقام الشائعة بالإملاء (نصف، واحد، اثنين ...)
const NUM_WORDS = { 'نص': '0.5', 'نصف': '0.5', 'واحد': '1', 'سنتي': '2', 'اثنين': '2', 'اثنان': '2', 'ثلاثة': '3', 'ثلاث': '3', 'اربعة': '4', 'أربعة': '4', 'اربع': '4', 'خمسة': '5', 'خمس': '5' };

// مصطلحات الورشة → صيغة موحّدة
const TERMS = [
  [/تتوسع|توسع|توسيع|وسّع|وسع/g, 'توسيع'],
  [/قصّر|تقصير|قصر/g, 'تقصير'],
  [/القالب|قالب/g, 'القالب'],
  [/خياطه|خياطة|خيّاطة/g, 'خياطة'],
  [/نعل|النعل/g, 'نعل'],
  [/دبل|مزدوج/g, 'دبل'],
  [/غراء|لصق|الصق|لصقت/g, 'غراء'],
  [/صبغ|صباغه|صباغة|صبغه/g, 'صبغ'],
  [/تلميع|لمّع|لمع/g, 'تلميع'],
  [/كعب/g, 'كعب'],
  [/بطانه|بطانة/g, 'بطانة'],
  [/سحاب|سوستة|سوسته/g, 'سحاب'],
  [/تنظيف|نظّف|نظف/g, 'تنظيف'],
  [/سنتيمتر|سنتي|سنتم|سم/g, 'سم'],
  [/مليمتر|ملم/g, 'مم'],
];
const DONE_RE = /(تم\s*الإ?نجاز|تم\s*العمل|خلّ?صت|خلص(ت|نا)?|انتهي(ت|نا)|القطعة\s*جاهزة|جاهز(ة)?\s*للتسليم|اقفل\s*الطلب|اقفلي?\s*الطلب)/;

export function parseDictation(raw) {
  let t = toLatinDigits(String(raw || '')).replace(/[٫,]/g, '.').trim();
  const done = DONE_RE.test(t);
  t = t.replace(new RegExp(DONE_RE.source, 'g'), ' ');
  for (const [re, to] of TERMS) t = t.replace(re, to);
  // "نص سم" / "اثنين سم" → رقم
  t = t.replace(/(^|\s)(نصف|نص|واحد|اثنين|اثنان|سنتي|ثلاثة|ثلاث|اربعة|أربعة|اربع|خمسة|خمس)\s+(?=سم|مم)/g, (m, a, w) => `${a}${NUM_WORDS[w]} `);
  t = t.replace(/\s*(?:\sثم|\sبعدين|\sوبعدين|\sو)\s*(?=(توسيع|تقصير|خياطة|غراء|صبغ|تلميع|كعب|بطانة|سحاب|تنظيف))/g, '، ');
  t = t.replace(/(\d+(?:\.\d+)?)\s*(سم|مم)/g, '$1 $2').replace(/\s{2,}/g, ' ').replace(/^[\s،]+|[\s،]+$/g, '');
  return { text: t, done };
}
